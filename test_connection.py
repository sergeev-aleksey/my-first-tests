# Импортируем модуль socket — он встроен в Python,
# ничего дополнительно ставить не нужно.
import socket

# Импортируем pytest — нужен для запуска тестов.
# Устанавливается командой: pip install pytest
import pytest

# Адрес и порт сервиса-симулятора (из исходных данных).
HOST = "127.0.0.1"   # localhost — сервис на этой же машине
PORT = 2001          # порт из задания


def test_connection_to_service():
    """
    Проверяем самый критичный сценарий:
    при подключении к сервису-симулятору соединение устанавливается.
    """

    # Создаём TCP-сокет.
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)

    # Даём сокету 3 секунды на попытку подключения,
    # чтобы тест не завис навсегда, если сервис не отвечает.
    sock.settimeout(3)

    # Пытаемся подключиться к сервису.
    # Если сервис недоступен — здесь будет исключение, и тест упадёт.
    sock.connect((HOST, PORT))

    # Проверка (assert): сокет действительно подключён.
    # getpeername() возвращает адрес удалённой стороны,
    # если соединение установлено.
    assert sock.getpeername() == (HOST, PORT), "Соединение не установлено"

    # Закрываем соединение — убираем за собой.
    sock.close()